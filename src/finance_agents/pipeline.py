"""Pipeline: data -> analysts -> bull/bear debate -> risk -> decision.

Returns a dict with every intermediate note plus a rendered Markdown
report, so both the CLI and the Streamlit UI can present the full
reasoning trail (the demo's main selling point: transparent agents).
"""
from __future__ import annotations

from . import agents as A
from .config import get_settings
from .data import build_data_provider
from .llm import build_llm

DISCLAIMER = (
    "Educational demo only — not financial advice. Market data is fetched "
    "from Yahoo Finance via yfinance (or clearly-labelled synthetic mock "
    "data when the fetch fails), and the analysis is generated by an AI "
    "model — the report header's \"LLM:\" line states exactly which "
    "provider produced it. AI analysis can be wrong."
)


def run_pipeline(ticker: str, settings=None, progress=None) -> dict:
    settings = settings or get_settings()
    llm = build_llm(settings)
    data = build_data_provider(settings)

    def step(msg: str):
        if progress:
            progress(msg)

    ticker = ticker.upper().strip()
    step(f"Fetching data for {ticker} ({data.name})")
    market = data.market_snapshot(ticker)
    fundamentals = data.fundamentals(ticker)
    news = data.news(ticker)

    step("Market analyst")
    market_note = A.MarketAgent(llm).run(market)
    step("Fundamentals analyst")
    fund_note = A.FundamentalsAgent(llm).run(fundamentals)
    step("News / sentiment analyst")
    news_note = A.NewsSentimentAgent(llm).run({"headlines": news})

    shared = {
        "ticker": ticker,
        "market_note": market_note,
        "fundamentals_note": fund_note,
        "sentiment_note": news_note,
    }
    step("Bull researcher")
    bull = A.BullAgent(llm).run(shared)
    step("Bear researcher")
    bear = A.BearAgent(llm).run({**shared, "bull_case": bull})
    step("Risk manager")
    risk = A.RiskAgent(llm).run({**shared, "bull_case": bull, "bear_case": bear})
    step("Portfolio manager (final decision)")
    decision = A.DecisionAgent(llm).run(
        {**shared, "bull_case": bull, "bear_case": bear, "risk_note": risk}
    )

    company = fundamentals.get("company_name")
    step(f"Data ready: {market.get('source')}"
         + (f" — {company}" if company else ""))
    result = {
        "ticker": ticker,
        "llm": llm.name,
        "llm_label": getattr(llm, "label", llm.name),
        "data_source": market.get("source"),
        "data_as_of": market.get("as_of"),
        "used_fallback": any(
            bool(d.get("used_fallback"))
            for d in (market, fundamentals)
        ),
        "fundamentals_source": fundamentals.get("source"),
        "market": market,
        "fundamentals": fundamentals,
        "news": news,
        "market_note": market_note,
        "fundamentals_note": fund_note,
        "sentiment_note": news_note,
        "bull_case": bull,
        "bear_case": bear,
        "risk_note": risk,
        "decision": decision,
    }
    result["report_md"] = render_markdown(result)
    return result


def _fmt(value, suffix=""):
    return f"{value}{suffix}" if value is not None else "n/a"


def render_markdown(r: dict) -> str:
    d, m, f = r["decision"], r["market"], r["fundamentals"]
    company = f.get("company_name")
    title = f"# {r['ticker']} — Multi-Agent Investment Report"
    if company:
        title += f"\n\n**{company}**"
    as_of = f" · prices as of {r['data_as_of']}" if r.get("data_as_of") else ""
    currency = f" {m['currency']}" if m.get("currency") else ""
    headlines = "\n".join(
        f"- {n['headline']}" + (f" ({n['publisher']})" if n.get("publisher") else "")
        for n in r["news"]
    )
    lines = [
        title,
        "",
        f"**Decision: {d['rating']}** · confidence {d['confidence']:.0%} · "
        f"LLM: {r.get('llm_label', r['llm'])} · Data: {r['data_source']}{as_of}",
        "",
        f"> {d['summary']}",
        "",
        f"Price {m['price']}{currency} · 1d {_fmt(m['change_pct_1d'], '%')} · "
        f"3m {_fmt(m['change_pct_3m'], '%')} · "
        f"EMA10 {_fmt(m.get('ema_10'))} · SMA50 {_fmt(m['sma_50'])} · "
        f"SMA200 {_fmt(m['sma_200'])} · RSI14 {_fmt(m['rsi_14'])} · "
        f"MACD hist {_fmt(m.get('macd_hist'))} · ATR14 {_fmt(m.get('atr_14'))} · "
        f"support {_fmt(m.get('support_60d'))} / resistance {_fmt(m.get('resistance_60d'))}",
        "",
        f"Fundamentals: P/E {_fmt(f.get('pe_ratio'))} · PEG {_fmt(f.get('peg_ratio'))} · "
        f"revenue growth {_fmt(f.get('revenue_growth_yoy_pct'), '% YoY')} · "
        f"gross margin {_fmt(f.get('gross_margin_pct'), '%')} · "
        f"ROE {_fmt(f.get('roe_pct'), '%')} · "
        f"debt/equity {_fmt(f.get('debt_to_equity'))} · "
        f"FCF {_fmt(f.get('free_cash_flow_bn'), 'bn')}"
        + (f" {m['currency']}" if f.get("free_cash_flow_bn") is not None and m.get("currency") else ""),
        "",
        "## Recent headlines", headlines or "_(none)_",
        "",
        "## Market Analyst", r["market_note"], "",
        "## Fundamentals Analyst", r["fundamentals_note"], "",
        "## News & Sentiment", r["sentiment_note"], "",
        "## Bull Case", r["bull_case"], "",
        "## Bear Case", r["bear_case"], "",
        "## Risk Management", r["risk_note"], "",
        "---",
        f"*{DISCLAIMER}*",
    ]
    return "\n".join(lines)
